// Precompiles the UI kit JSX sources into one plain script per kit (ui_kits/<kit>/kit.js).
// Why: compiling JSX in the browser needs Babel standalone (3 MB) and the development build of React (1.1 MB) on every visit.
// The JSX files stay the source of truth. Run this after editing any of them; `--check` exits 1 if a kit.js is stale.
// Setup: npm i @babel/standalone   Usage: node scripts/build-kits.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const Babel = require('@babel/standalone');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
// Files in load order. Each one publishes what it shares with Object.assign(window, { ... }).
const KITS = {
  website: ['KitIcon.jsx', 'SiteHeader.jsx', 'Hero.jsx', 'Workflows.jsx', 'Features.jsx', 'Proof.jsx', 'ChatWidget.jsx', 'App.jsx'],
  'roi-calculator': ['RoiCalculator.jsx'],
};
let stale = false;
for (const [kit, files] of Object.entries(KITS)) {
  const dir = path.join(root, 'ui_kits', kit);
  let out = `/* Generated by scripts/build-kits.mjs from ${files.join(', ')}. Do not edit: edit the JSX and rebuild. */\n`;
  for (const f of files) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    const { code } = Babel.transform(src, { presets: [['react', { runtime: 'classic' }]], filename: f, compact: false, comments: false });
    out += `\n// ${f}\n(function () {\n${code}\n})();\n`;
  }
  const target = path.join(dir, 'kit.js');
  const norm = (s) => s.replace(/\r\n/g, '\n');
  const current = fs.existsSync(target) ? norm(fs.readFileSync(target, 'utf8')) : '';
  if (current === norm(out)) { console.log(`ui_kits/${kit}/kit.js up to date`); continue; }
  if (check) { stale = true; console.log(`ui_kits/${kit}/kit.js is STALE: run node scripts/build-kits.mjs`); continue; }
  fs.writeFileSync(target, out);
  console.log(`ui_kits/${kit}/kit.js written (${Math.round(out.length / 1024)}k)`);
}
process.exit(stale ? 1 : 0);
